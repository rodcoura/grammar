export const getTranslator = (languageCode: string | null | undefined) => {
  const currentLang = languageCode && translations[languageCode] ? languageCode : DEFAULT_LANGUAGE_CODE;
  const fallbackLang = DEFAULT_LANGUAGE_CODE;

  return (key: TranslationKey, defaultText?: string): string => {
    const translated = translations[currentLang]?.[key] || translations[fallbackLang]?.[key] || defaultText || key;
    return translated;
  };
};
